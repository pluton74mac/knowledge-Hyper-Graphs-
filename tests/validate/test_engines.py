def _subschemas(s, path=""):
    """Every subschema of a schema document (the positions the generator propagates codes to)."""
    if not isinstance(s, dict):
        return
    yield path, s
    for k in CHILD_MAPS:
        for name, v in (s.get(k) or {}).items():
            yield from _subschemas(v, f"{path}/{k}/{name}")
    for k in CHILD_ONE:
        if isinstance(s.get(k), dict):
            yield from _subschemas(s[k], f"{path}/{k}")
    for k in CHILD_LIST:
        for i, v in enumerate(s.get(k) or []):
            yield from _subschemas(v, f"{path}/{k}/{i}")
    for name, v in (s.get("dependencies") or {}).items():
        yield from _subschemas(v, f"{path}/dependencies/{name}")


def _failing_keywords(sub):
    """The keywords of a subschema that fail as themselves (a schema-valued additionalProperties,
    propertyNames or dependency fails through its own subschema)."""
    for keyword in sorted(CONSTRAINT_KEYS & set(sub)):
        value = sub[keyword]
        if keyword == "propertyNames" or keyword == "additionalProperties" and isinstance(value, dict):
            continue
        if keyword == "dependencies" and all(isinstance(v, dict) for v in value.values()):
            continue
        yield keyword


@pytest.mark.parametrize("sid", OURS)
def test_every_constraint_names_a_registered_active_code_of_its_layer(sid):
    """The coverage test of §8.1: the generator propagated a code to every constraint-bearing subschema."""
    reg = registry()
    doc = data.schema_documents()[sid]
    seen, checked = set(), 0
    for path, sub in _subschemas(doc):
        for keyword in _failing_keywords(sub):
            checked += 1
            code = engines.code_of(sub, keyword)
            assert code is not None, f"{sid}{path}: {keyword} has no x-khg-code"
            assert code in reg and reg[code].active, (sid, path, keyword, code)
            seen.add(code)
    assert checked > 20
    assert {reg[c].layer for c in seen} == LAYER_OF_SCHEMA[sid]


#: The disjunctions of the C4 draft (W11a): an instant or null, and a put or an apply event. They carry I002.
C4_DISJUNCTIONS = ["/allOf/3/then/properties/where/properties/as_of", "/allOf/4/then/properties/events/items",
                   "/allOf/5/then/allOf/0/properties/where/properties/as_of"]


@pytest.mark.parametrize("sid", OURS)
def test_if_then_dispatch_replaces_one_of_and_any_of(sid):
    """No oneOf or anyOf outside a ``not`` (a negated disjunction fails as ``not``), except in the C4 draft,
    whose three disjunctions carry their own code."""
    doc = data.schema_documents()[sid]
    found = [p for p, sub in _subschemas(doc) if ("oneOf" in sub or "anyOf" in sub) and "/not" not in p]
    if sid == engines.C4_SCHEMA_ID:
        assert found == C4_DISJUNCTIONS
        for p, sub in _subschemas(doc):
            if p in found:
                keyword = "oneOf" if "oneOf" in sub else "anyOf"
                assert engines.code_of(sub, keyword) == "KHG-I002"
    else:
        assert found == []


def test_code_of_reads_a_code_or_a_keyword_map():
    assert engines.code_of({"x-khg-code": "KHG-C003"}, "type") == "KHG-C003"
    m = {"x-khg-code": {"default": "KHG-C010", "enum": "KHG-C002"}}
    assert engines.code_of(m, "enum") == "KHG-C002" and engines.code_of(m, "type") == "KHG-C010"
    assert engines.code_of({"x-khg-code": {"enum": "KHG-C002"}}, "type") is None
    assert engines.code_of({"type": "string"}, "type") is None and engines.code_of(True, "type") is None


