@pytest.mark.parametrize("engine", ENGINES)
@pytest.mark.parametrize("root", ROOTS)
def test_every_packaged_schema_compiles_offline_and_accepts_the_packaged_files(root, engine):
    runner = engines.compile_schema(root, engine=engine)
    assert runner is engines.compile_schema(root, engine=engine)  # cached
    for rel in GOOD[root]:
        instances = data.load_jsonl(rel) if rel.endswith(".jsonl") else [data.load_json(rel)]
